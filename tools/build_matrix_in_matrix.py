"""构建 matrix-in-matrix 示例：将程序嵌入 VM，再将该 VM 嵌入外层 VM。

生成文件只包含嵌入镜像、对 c4vm.c 的 include 和 main；解释器逻辑始终来自
同一份 c4vm.c。此工具生成两层 C 包装程序，最终的原生构建仍由 GCC 完成。
"""

import argparse
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
# 直接从任意工作目录执行此脚本时，也能导入根目录的编译器。
sys.path.insert(0, str(ROOT))
import compiler
import packer

VM_SOURCE = ROOT / "c4vm.c"
INNER_STACK_QWORDS = 512
OUTER_STACK_QWORDS = 4096


def compile_to_qwords(source_path):
    """嵌入的是原始镜像；.vm 文件的容量头不属于指令流。"""
    return packer.qword_array(compiler.compile_raw(source_path))


def write_embedded_program(image_qwords, stack_qwords, out_path):
    """生成含镜像和向下增长栈的包装程序，栈容量的单位为 8 字节字。"""
    if not isinstance(stack_qwords, int) or stack_qwords < 4:
        raise ValueError("embedded stack must contain at least four qwords")
    out_path = Path(out_path).resolve()
    # 使用相对 include，同时供系统 C 编译器和项目预处理器解析。
    try:
        include = Path(os.path.relpath(VM_SOURCE, out_path.parent)).as_posix()
    except ValueError:
        # Windows 输出目录与仓库可能不在同一个盘符，此时无法构造相对路径。
        include = VM_SOURCE.as_posix()
    if any(character in include for character in '\n\r"'):
        raise ValueError("VM include path cannot contain quotes or newlines")
    values = list(image_qwords) + [0] * stack_qwords
    # INT64_MIN 的绝对值不是有符号 C 字面量；拆成两个合法值，兼容严格警告构建。
    literals = ["(-9223372036854775807-1)" if value == -(1 << 63) else str(value) for value in values]
    source = (
        "/* Generated by tools/build_matrix_in_matrix.py; rebuild instead of editing. */\n"
        "#define C4VM_EMBEDDED\n"
        f'#include "{include}"\n\n'
        "/* main has no guest argc/argv; the zero tail reserves its VM stack. */\n"
        "int main(void) {\n"
        f"    long long code[{len(values)}] = {{{','.join(literals)}}};\n"
        "    return load_mem(code, sizeof(code));\n"
        "}\n"
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(source, encoding="utf-8")
    return out_path


def build_matrix_in_matrix(source_path, output_dir, inner_stack=INNER_STACK_QWORDS,
                          outer_stack=OUTER_STACK_QWORDS):
    """先包装用户程序，再编译第一层包装程序作为外层 VM 的载荷。"""
    output_dir = Path(output_dir).resolve()
    if Path(source_path).resolve() in [output_dir / "matrix.c", output_dir / "matrix_in_matrix.c"]:
        raise ValueError("input source must not be one of the generated output files")
    inner = write_embedded_program(compile_to_qwords(source_path), inner_stack, output_dir / "matrix.c")
    outer = write_embedded_program(compile_to_qwords(inner), outer_stack, output_dir / "matrix_in_matrix.c")
    return inner, outer


def main(argv=None):
    cli = argparse.ArgumentParser(description="Generate C programs for matrix-in-matrix execution")
    cli.add_argument("source", nargs="?", type=Path, default=ROOT / "hi.c")
    cli.add_argument("--output-dir", type=Path, default=ROOT / "build" / "matrix-in-matrix")
    cli.add_argument("--inner-stack-qwords", type=int, default=INNER_STACK_QWORDS)
    cli.add_argument("--outer-stack-qwords", type=int, default=OUTER_STACK_QWORDS)
    args = cli.parse_args(argv)
    try:
        paths = build_matrix_in_matrix(args.source, args.output_dir,
                                       args.inner_stack_qwords, args.outer_stack_qwords)
    except (OSError, SyntaxError, ValueError, OverflowError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for path in paths:
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
